"""lib/nginx_converter.py — convert a plain nginx conf to a Jinja2 .j2 template.

Transformations applied
-----------------------
directive           before                              after
---------           ------                              -----
server_name         server_name example.com;            server_name {{ hostname }};
server_name         server_name web_hostname--neo4j;    server_name {{ hostname_stem }}--neo4j.{{ domain_name }};
                    (a name carrying `--` — R1.5's extra HTTP endpoint — keeps its
                     sub-service instead of collapsing to the instance host)
auth_basic          auth_basic "My App";                auth_basic "{{ service_name }} - {{ user_name }}";
auth_basic_user_file auth_basic_user_file /etc/...;     auth_basic_user_file {{ htpasswd_path }};
proxy_pass          proxy_pass http://web:80;           proxy_pass http://{{ container_prefix }}web:80;
                    (only when host matches a compose service name exactly)

All other content is preserved verbatim.  ${ENV_VAR} expressions are left
untouched — they are resolved by nginx at runtime via environment substitution.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Any

_HEADER_TPL = """\
# {stem}.nginx.conf.j2 — generated by gen_nginx_template.py
#
# Template variables resolved at registration time by user_provision_tool:
#   {{{{ hostname }}}}          e.g. {hint}-alice-0.example.com
#   {{{{ container_prefix }}}}  e.g. {hint}-user_alice-0-
#   {{{{ htpasswd_path }}}}     absolute path to the generated .htpasswd file
#   {{{{ user_name }}}}
#   {{{{ service_name }}}}
#   {{{{ label }}}}
#   {{{{ domain_name }}}}
#   {{{{ network_name }}}}
#   {{{{ https }}}}             boolean, True when HTTPS is enabled
#   {{{{ ssl_certificate_path }}}}      /provision/ssl/{{{{ domain_name }}}}/fullchain.pem
#   {{{{ ssl_certificate_key_path }}}}  /provision/ssl/{{{{ domain_name }}}}/privkey.pem
#
# NOTE: proxy_pass targets that exactly match a compose service name have
#   been rewritten to {{{{ container_prefix }}}}<name>.  Any host that does
#   not match a compose service name is left unchanged — review and adjust
#   remaining literal container names manually.
#
# NOTE: ssl_certificate and ssl_certificate_key paths have been replaced with
#   template variables.  Wrap HTTPS server blocks in {{% if tls %}}...{{% endif %}}
#   to conditionally enable TLS.
#
"""


# ---------------------------------------------------------------------------
# Certificate coverage and access policy (task doc R5-R9, R11)
#
# The -api owns certificate material and the platform's network policy. Both
# are applied here, to a plain conf AND to a selected `.j2` template, so the
# operator never has to know either.
# ---------------------------------------------------------------------------

CERT_PAIR_LINES = (
    "ssl_certificate     {{ ssl_certificate_path }};\n"
    "ssl_certificate_key {{ ssl_certificate_key_path }};\n"
)

# One certificate directive, anywhere a directive can start.  The value may be
# empty — an empty value is an INCOMPLETE pair and is replaced, not coverage.
_CERT_RE = re.compile(
    r"(?<![\w-])(ssl_certificate(?:_key)?)([ \t]+)([^;\n]*?)([ \t]*;)"
)

# Any access rule, at any depth: a standalone line OR one that follows a `;`,
# `{` or `}` on the same line (a one-line `location / { …; deny all; }`).
# The word in a comment is untouched, because `#` is not a delimiter we accept.
_POLICY_RE = re.compile(
    r"(?m)^[ \t]*(?:allow|deny)[ \t]+[^;\n]*;[ \t]*(?:\r?\n)?"
    r"|([;{}])[ \t]*(?:allow|deny)[ \t]+[^;\n]*;"
)

_INCLUDE_RE = re.compile(r"^[ \t]*include[ \t]+([^;\n]+);", re.MULTILINE)

# A TLS listener.  Not line-anchored: a one-line `server { listen 443 ssl; … }`
# is a real shape, and the converter must see it.
_TLS_LISTEN_RE = re.compile(
    r"(?<![\w-])listen[ \t]+[^;{}]*\bssl\b[^;{}]*;"
)


def _mask_nested(block: str) -> str:
    """Blank out everything below the server block's own level.

    Directive detection runs over this, so a `ssl_certificate` inside a nested
    `location` is not mistaken for the block's own pair and a policy line inside
    one is not mistaken for a top-level rule.  Character count is preserved, so
    match offsets still address the original text.
    """
    out: list[str] = []
    depth = 0
    i = 0
    while i < len(block):
        # Jinja expressions are values, not block structure: `{{ var }}` must
        # not be mistaken for nested braces, or every templated value would be
        # masked away and read as empty.
        if block.startswith("{{", i):
            out.append("{{")
            i += 2
            continue
        if block.startswith("}}", i):
            out.append("}}")
            i += 2
            continue
        ch = block[i]
        if ch == "{":
            depth += 1
            out.append(ch if depth == 1 else " ")
        elif ch == "}":
            out.append(" " if depth > 1 else ch)
            depth -= 1
        elif depth <= 1:
            out.append(ch)
        else:
            out.append("\n" if ch == "\n" else " ")
        i += 1
    return "".join(out)


def _top_cert_matches(block: str) -> list["re.Match[str]"]:
    return list(_CERT_RE.finditer(_mask_nested(block)))


def _top_policy_matches(block: str) -> list["re.Match[str]"]:
    """Stream policy rules at the block's own level (nested content masked)."""
    return list(_POLICY_RE.finditer(_mask_nested(block)))


def _remove_spans(text: str, spans: list[tuple[int, int]]) -> str:
    for start, end in sorted(spans, reverse=True):
        text = text[:start] + text[end:]
    return text


def _split_server_blocks(t: str) -> list[dict[str, Any]]:
    """Split conf text into server blocks and the text between them.

    Brace counting, because a regex cannot balance.  The non-server chunks keep
    the file-level directives — which is what tells an HTTP conf's inherited
    certificate pair from a stream conf's invalid one.
    """
    blocks = re.split(r'(^[ \t]*server\s*\{)', t, flags=re.MULTILINE)
    result: list[dict[str, Any]] = []
    i = 0
    while i < len(blocks):
        chunk = blocks[i]
        if re.match(r'^[ \t]*server\s*\{', chunk):
            block = chunk
            depth = chunk.count('{') - chunk.count('}')
            i += 1
            while i < len(blocks) and depth > 0:
                next_chunk = blocks[i]
                depth += next_chunk.count('{') - next_chunk.count('}')
                block += next_chunk
                i += 1
            result.append({"is_server": True, "text": block})
        else:
            if chunk:
                result.append({"is_server": False, "text": chunk})
            i += 1
    return result


def _join_parts(parts: list[dict[str, Any]]) -> str:
    return "".join(p["text"] for p in parts)


def _top_level_lines(block: str) -> list[tuple[int, str]]:
    """`(index, line)` for every line at the server block's OWN level.

    Lines inside a nested `location`/`if` are excluded: a certificate directive
    there is not coverage for the block, and a policy line there is still an
    access rule (the HTTP remover does not use this helper — it removes at any
    depth).
    """
    lines = block.splitlines(keepends=True)
    out: list[tuple[int, str]] = []
    depth = 0
    for i, line in enumerate(lines):
        before = depth
        depth += line.count("{") - line.count("}")
        if before == 1:
            out.append((i, line))
    return out


def _pair_complete(matches: list["re.Match[str]"]) -> bool:
    """Exactly one non-empty certificate AND one non-empty key."""
    certs = [m for m in matches
             if m.group(1) == "ssl_certificate" and m.group(3).strip()]
    keys = [m for m in matches
            if m.group(1) == "ssl_certificate_key" and m.group(3).strip()]
    return len(certs) == 1 and len(keys) == 1


def _rewrite_cert_values(text: str) -> str:
    """A visible certificate path becomes the template variable.

    Idempotent: a value that already IS the variable is left byte-identical, so
    converting a normalized template a second time cannot double-substitute.
    """
    def _repl(m: "re.Match[str]") -> str:
        name, sep, value, tail = m.groups()
        var = ("ssl_certificate_path" if name == "ssl_certificate"
               else "ssl_certificate_key_path")
        if value.strip() == "{{ %s }}" % var:
            return m.group(0)
        return name + sep + "{{ " + var + " }}" + tail

    return _CERT_RE.sub(_repl, text)


def _line_span(text: str, m: "re.Match[str]") -> tuple[int, int]:
    """The directive's span, widened to its whole line when it is alone there.

    Removing a whole standalone line leaves no blank line — which is what makes
    the policy/certificate passes byte-idempotent when they run twice.
    """
    start, end = m.start(), m.end()
    line_start = text.rfind("\n", 0, start) + 1
    # A match that already ends at a line boundary (the policy regexes include
    # the newline) must not be widened again — it would eat the next line.
    if end > 0 and text[end - 1] == "\n":
        return (line_start if text[line_start:start].strip() == "" else start), end
    line_end = text.find("\n", end)
    if text[line_start:start].strip() == "" and (
        line_end < 0 or text[end:line_end].strip() == ""
    ):
        return line_start, (line_end + 1 if line_end >= 0 else len(text))
    return start, end


def _strip_top_level_cert_lines(block: str) -> str:
    spans = [_line_span(block, m) for m in _top_cert_matches(block)]
    return _remove_spans(block, spans)


def _strip_cert_from_fragment(fragment: str) -> str:
    """Remove file-level certificate directives (invalid outside a server block
    in a stream conf; replaced on the blocks themselves)."""
    spans = [_line_span(fragment, m) for m in _CERT_RE.finditer(fragment)]
    return _remove_spans(fragment, spans)


def _inject_after(text: str, m: "re.Match[str]", lines: str) -> str:
    """Insert whole `lines` immediately after a directive match."""
    line_start = text.rfind("\n", 0, m.start()) + 1
    lead = text[line_start:m.start()]
    indent = lead if lead.strip() == "" else "    "
    body = "".join(indent + ln for ln in lines.splitlines(keepends=True))
    tail = text[m.end():]
    if tail.startswith("\r\n"):
        tail = tail[2:]
    elif tail.startswith("\n"):
        tail = tail[1:]
    return text[:m.end()] + "\n" + body + tail


def _inject_cert_pair(block: str) -> str:
    """Insert the deploy pair immediately after the block's TLS listen line."""
    m = _TLS_LISTEN_RE.search(block)
    if not m:
        return block
    return _inject_after(block, m, CERT_PAIR_LINES)


def _has_opaque_include(text: str) -> bool:
    """Does the file include something the converter cannot see into?

    The known v4 scaffold (`/etc/nginx/env.d/*.env`) is removed at render, so
    it is not opaque; every other include is.
    """
    for m in _INCLUDE_RE.finditer(text):
        target = m.group(1).strip().strip('"\'')
        if not target.endswith("env.d/*.env"):
            return True
    return False


def remove_http_policy(text: str) -> str:
    """R11 — every `allow`/`deny` directive, at any depth, is gone. None is added."""
    return _remove_http_policy(text)


def _remove_http_policy(text: str) -> str:
    """R11 — every `allow`/`deny` directive, at any depth, is gone. None is added.

    Repeated until stable: on a one-line `…; allow a; deny all; }` the first
    pass consumes `; allow a;`, and the `deny` that followed it now sits behind
    the retained `;` — the next pass sees it.
    """
    def _repl(m: "re.Match[str]") -> str:
        return m.group(1) or ""

    for _ in range(10):
        new = _POLICY_RE.sub(_repl, text)
        if new == text:
            return text
        text = new
    return text


def _cover_http_certs(text: str) -> str:
    """R5/R6/R9 for the HTTP category.

    A complete file-level pair covers every block (the file is included inside
    `http {}`, so the directive is inherited); otherwise each TLS block needs
    its own pair.  A partial pair is replaced, never completed by guessing.
    """
    text = _rewrite_cert_values(text)
    parts = _split_server_blocks(text)

    file_matches: list["re.Match[str]"] = []
    for p in parts:
        if not p["is_server"]:
            file_matches.extend(_CERT_RE.finditer(p["text"]))
    file_complete = _pair_complete(file_matches)

    if file_matches and not file_complete:
        for p in parts:
            if not p["is_server"]:
                p["text"] = _strip_cert_from_fragment(p["text"])

    opaque = _has_opaque_include(text)
    out: list[dict[str, Any]] = []
    for p in parts:
        if not p["is_server"]:
            out.append(p)
            continue
        block = p["text"]
        if not _TLS_LISTEN_RE.search(block):
            out.append({"is_server": True, "text": block})
            continue
        matches = _top_cert_matches(block)
        if _pair_complete(matches):
            out.append({"is_server": True, "text": block})
            continue
        if matches:
            block = _strip_top_level_cert_lines(block)
            if not file_complete:
                block = _inject_cert_pair(block)
            out.append({"is_server": True, "text": block})
            continue
        if file_complete:
            out.append({"is_server": True, "text": block})
            continue
        if opaque:
            raise ValueError(
                "uncovered TLS server block in a conf that contains an `include` — "
                "the -api cannot see the included certificate, so the deployment's "
                "pair cannot be guaranteed; remove the include or name the pair "
                "in this file"
            )
        out.append({"is_server": True, "text": _inject_cert_pair(block)})
    return _join_parts(out)


def _strip_top_level_policy(block: str) -> str:
    """Remove every top-level `allow`/`deny` from a stream server block.

    The platform's stream policy is a single stream-context list
    (`stream-access.conf` + the static `deny all;`). A per-server list would
    OVERRIDE that inherited list entirely, so an operator's rule must be
    removed here rather than replaced.
    """
    spans = [_line_span(block, m) for m in _top_policy_matches(block)]
    return _remove_spans(block, spans)


def remove_stream_policy(text: str) -> str:
    """Remove per-server AND file-level policy from a stream conf.

    The file is included inside `stream {}`, so a file-level `allow`/`deny` is a
    stream-context rule; leaving it would add a second policy beside the one
    `stream-access.conf`. Both forms are removed. A stream `server{}` has no
    nested contexts in which an access rule would be valid, so the server-level
    rule is removed at its own level.
    """
    parts = _split_server_blocks(text)
    for p in parts:
        if p["is_server"]:
            p["text"] = _strip_top_level_policy(p["text"])
        else:
            p["text"] = _remove_http_policy(p["text"])
    return _join_parts(parts)


def _stream_cert_and_policy(text: str) -> str:
    """R5/R9 and policy removal for the stream category.

    A stream conf has NO file-level certificate context: `ssl_certificate` is a
    server-context directive in the stream module, so a file-level pair is
    removed rather than treated as coverage.  Every block is covered only by
    its own pair.  All per-server `allow`/`deny` is REMOVED: the platform policy
    is one stream-context list, and a per-server list would override it.
    """
    parts = _split_server_blocks(text)
    for p in parts:
        if not p["is_server"]:
            # File-level certificate lines are invalid in the stream context;
            # a file-level allow/deny would become a stream-context rule beside
            # the central policy, so both are removed here.
            p["text"] = _remove_http_policy(_strip_cert_from_fragment(p["text"]))
    text = _rewrite_cert_values(_join_parts(parts))
    opaque = _has_opaque_include(text)

    parts = _split_server_blocks(text)
    out: list[dict[str, Any]] = []
    for p in parts:
        if not p["is_server"]:
            out.append(p)
            continue
        block = p["text"]
        if _TLS_LISTEN_RE.search(block):
            matches = _top_cert_matches(block)
            if not _pair_complete(matches):
                if matches:
                    block = _inject_cert_pair(_strip_top_level_cert_lines(block))
                elif opaque:
                    raise ValueError(
                        "uncovered TLS stream block in a conf that contains an "
                        "`include` — the -api cannot see the included certificate"
                    )
                else:
                    block = _inject_cert_pair(block)
        out.append({"is_server": True, "text": _strip_top_level_policy(block)})
    return _join_parts(out)


_SERVER_NAME_RE = re.compile(r"([ \t]*server_name[ \t]+)([^\n;]+)(;)")


def _bare_http_server_name(text: str) -> str:
    """The first `server_name` value that names no `--<sub_service>` endpoint.

    R14 — the instance hostname is identity, not a route: every served HTTP
    endpoint carries the reserved separator.  A name line is acceptable when
    its literal residue (template expressions removed) contains a token with
    `--`; `{{ hostname }}`, `mock_server_name` and a concrete instance host are
    all bare, and a NEW selection carrying one is refused rather than silently
    dropped.
    """
    for m in _SERVER_NAME_RE.finditer(text or ""):
        raw = m.group(2).strip()
        residue = re.sub(r"\{\{.*?\}\}", "", raw)
        tokens = [t for t in residue.split() if t]
        if not tokens:
            return raw
        if any("--" not in t for t in tokens):
            return raw
    return ""


def reject_bare_http_server_names(text: str) -> None:
    """Raise when an HTTP conf/template has a bare (no-`--`) server name (R14)."""
    bare = _bare_http_server_name(text)
    if bare:
        raise ValueError(
            f"server_name {bare!r} names no `--<sub_service>` endpoint — every "
            "HTTP endpoint is served at `<instance host>--<sub_service>.<domain>`; "
            "the instance hostname is identity, not a route (R14)"
        )


def strip_unserved_http_blocks(text: str) -> str:
    """Drop every `server{}` whose name carries no `--<sub_service>` (R14).

    Used for EXISTING rendered confs (the migration) and as a render-time guard:
    a legacy template still produces its bare primary block, and that block must
    not become a route for the old instance host.  A block with no
    `server_name` at all is dropped too — it would serve any host.
    """
    parts = _split_server_blocks(text or "")
    out: list[dict[str, Any]] = []
    for p in parts:
        if not p["is_server"]:
            out.append(p)
            continue
        m = _SERVER_NAME_RE.search(p["text"])
        if m and "--" in m.group(2):
            out.append(p)
    return _join_parts(out)


def migrate_rendered_http_confs(base_dir: str | Path | None = None) -> list[str]:
    """Strip bare primary blocks from existing rendered `*.nginx.conf` files.

    R14's compatibility half: confs rendered before the primary removal keep
    serving the instance host until they are rewritten.  Returns the paths that
    changed; the caller reloads once.
    """
    base = Path(base_dir) if base_dir is not None else os.environ.get("GENERATED_DIR", "")
    if not str(base) or not Path(base).is_dir():
        return []
    changed: list[str] = []
    for path in sorted(Path(base).glob("*.nginx.conf")):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        stripped = strip_unserved_http_blocks(text)
        if stripped == text:
            continue
        try:
            path.write_text(stripped, encoding="utf-8")
        except OSError:
            continue
        changed.append(str(path))
    return changed


def normalize_http_template(text: str) -> str:
    """Apply the HTTP certificate and policy rules to a selected `.j2`.

    No server_name, auth_basic or proxy rewriting: those are the converter's
    job on a PLAIN conf.  A template already carries its variables.  R14's
    bare-name refusal is the REGISTRATION route's (it refuses a new selection
    before this runs), so a legacy template can still be normalized for
    migration purposes.
    """
    return _cover_http_certs(_remove_http_policy(text))


def normalize_stream_template(text: str) -> str:
    """Apply the stream certificate and policy rules to a selected `.j2`."""
    return _stream_cert_and_policy(text)


def convert_nginx(
    text: str,
    service_name_hint: str = "",
    compose_service_names: list[str] | None = None,
) -> str:
    """Apply Jinja2 substitutions to the text of a plain nginx conf.

    Parameters
    ----------
    service_name_hint:
        Provision service name (used only for the generated header comment).
    compose_service_names:
        Service keys from the companion docker-compose.yml.  This is the
        **only** input used to rewrite proxy_pass targets.  Each host that
        exactly matches a compose service name is replaced with
        ``{{ container_prefix }}<name>`` so it resolves to the actual
        deployed container name at render time.

        If empty or ``None``, proxy_pass targets are left unchanged — the
        caller should review and adjust container names manually.
    """

    # server_name — a name carrying R1.5's reserved separator keeps its
    # sub-service and becomes `<instance stem>--<sub_service>.<domain>` (one
    # label under the domain, which is what lets the single wildcard certificate
    # serve it). R14 makes that the ONLY shape a NEW selection may carry: the
    # registration route refuses a bare name before conversion. The legacy
    # mapping below (bare → `{{ hostname }}`) stays for an already-converted
    # template being normalized: generated files are never auto-deleted.
    def _server_name(match: "re.Match[str]") -> str:
        head, token, tail = match.group(1), match.group(2), match.group(3)
        if "{{" in token or "{%" in token:
            # Already templated (a second conversion): leave it byte-exact.
            return head + token + tail
        parts: list[str] = []
        for name in token.split():
            if "--" in name:
                # Everything after the separator, minus any domain the model
                # wrote: a sub-service is a compose service key and carries no dot.
                sub = name.split("--", 1)[1].split(".")[0].strip()
                parts.append(
                    f"{{{{ hostname_stem }}}}--{sub}.{{{{ domain_name }}}}"
                    if sub else "{{ hostname }}"
                )
            else:
                parts.append("{{ hostname }}")
        return head + " ".join(parts) + tail

    text = re.sub(r'([ \t]*server_name[ \t]+)([^\n;]+)(;)', _server_name, text)

    # auth_basic string
    text = re.sub(
        r'([ \t]*auth_basic[ \t]+)"[^"]*"(;)',
        r'\1"{{ service_name }} - {{ user_name }}"\2',
        text,
    )

    # auth_basic_user_file path
    text = re.sub(
        r'([ \t]*auth_basic_user_file[ \t]+)\S+(;)',
        r'\1{{ htpasswd_path }}\2',
        text,
    )

    # R11 — HTTP access control is auth_basic and the edge; an operator's
    # allow/deny line is not part of the planned behaviour. Remove it BEFORE
    # the TLS synthesis below, so a cloned 443 block cannot inherit it.
    text = _remove_http_policy(text)

    # --- Build set of compose service names for fast lookup ---
    compose_names: set[str] = set()
    if compose_service_names:
        compose_names = {n.lower() for n in compose_service_names}

    # --- Wrap / auto-generate HTTPS server blocks ---
    _has_ssl_listen = bool(re.search(r'listen\s+[^;]*\bssl\b', text))
    if _has_ssl_listen:
        # Existing HTTPS blocks: wrap them + redirect blocks in {% if tls %}.
        # IDEMPOTENT: a block already preceded by a `{% if tls %}` guard (our
        # own output, or an operator's) is not wrapped again — conversion may
        # run twice on the same template (R7).
        parts = _split_server_blocks(text)
        out: list[str] = []
        for p in parts:
            if p["is_server"]:
                block = p["text"]
                needs_guard = bool(
                    re.search(r'listen\s+[^;]*\bssl\b', block)
                    or re.search(r'return\s+301\s+https://', block)
                )
                already_guarded = bool(out) and out[-1].rstrip().endswith("{% if tls %}")
                if needs_guard and not already_guarded:
                    out.append('\n{% if tls %}\n' + block + '\n{% endif %}\n')
                else:
                    out.append(block)
            else:
                out.append(p["text"])
        text = ''.join(out)
    else:
        # No HTTPS blocks in source → auto-generate them from HTTP blocks.
        parts = _split_server_blocks(text)
        out: list[str] = []
        for p in parts:
            if p["is_server"]:
                block = p["text"]
                # Only auto-generate HTTPS for blocks with listen 80 (not other ports).
                if re.search(r'listen\s+[^;]*\b80\b', block) and not re.search(r'listen\s+[^;]*\bssl\b', block):
                    https_block = block
                    # Replace listen 80 (with optional modifiers) → listen 443 ssl
                    https_block = re.sub(
                        r'listen\s+80(\s+[^;]*)?;',
                        r'listen 443 ssl\1;',
                        https_block,
                    )
                    # Inject ssl_certificate directives after the listen 443 ssl line
                    https_block = re.sub(
                        r'(listen\s+443\s+ssl[^;]*;)',
                        r'\1\n    ssl_certificate {{ ssl_certificate_path }};\n    ssl_certificate_key {{ ssl_certificate_key_path }};',
                        https_block,
                    )
                    out.append(block)
                    out.append('\n{% if tls %}\n' + https_block + '\n{% endif %}\n')
                else:
                    out.append(block)
            else:
                out.append(p["text"])
        text = ''.join(out)

    # R5/R6/R9 — certificates, AFTER any TLS block has been synthesized: an
    # untouched block inherits the file-level pair, an uncovered one receives
    # the deploy pair, and an include it cannot be seen through is refused.
    text = _cover_http_certs(text)

    # proxy_pass — rewrite host to {{ container_prefix }}<name> when it
    # exactly matches a compose service name.  This is deterministic: the
    # original docker-compose.yml defines the service names, and the
    # original nginx.conf references them.  No heuristics, no prefix stripping.
    if compose_names:

        def _repl_proxy(m: re.Match) -> str:
            scheme = m.group(1)      # "http://" or "https://"
            host = m.group(2)        # container name or hostname
            port_path = m.group(3)   # ":port" and/or "/path", may be empty
            tail = m.group(4)        # ";" or whitespace terminator

            if host.lower() in compose_names:
                return (
                    f"proxy_pass {scheme}"
                    f"{{{{ container_prefix }}}}{host}{port_path}{tail}"
                )
            return m.group(0)

        text = re.sub(
            r'proxy_pass\s+(https?://)([a-zA-Z0-9_-]+)((?::\d+)?(?:/[^\s;]*)?)(;)',
            _repl_proxy,
            text,
        )

    # --- Inject auth_basic into every server block that lacks it ---
    # Must run AFTER HTTPS block generation so that:
    #  - auto-generated HTTPS blocks (cloned from HTTP) also receive auth_basic
    #  - existing HTTPS blocks (wrapped in {% if tls %}) also receive auth_basic
    if not re.search(r'[ \t]*auth_basic\b', text):
        def _inject_auth(m: re.Match) -> str:
            indent = re.match(r'^([ \t]*)', m.group(0)).group(1)
            auth_lines = (
                indent + 'auth_basic "{{ service_name }} - {{ user_name }}";\n' +
                indent + 'auth_basic_user_file {{ htpasswd_path }};\n'
            )
            return auth_lines + m.group(0)

        parts = _split_server_blocks(text)
        out_blocks: list[str] = []
        for p in parts:
            if p["is_server"]:
                block = p["text"]
                # Inject auth_basic before the first proxy_pass in this server block
                block = re.sub(
                    r'([ \t]*)proxy_pass[ \t]+[^;]+;',
                    _inject_auth,
                    block,
                    count=1,
                )
                out_blocks.append(block)
            else:
                out_blocks.append(p["text"])
        text = ''.join(out_blocks)

    # ------------------------------------------------------------------
    # v4 (acl-enforcement-design-v4 §10.3 F2): the per-service conf is
    # byte-identical across modes, and the JWT/ACL scaffolding (set $auth_mode,
    # include env.d, auth_request, /__basic__/, @auth_401/@auth_403, the plain
    # _set_token proxy, the variable /_auth_jwt) is injected by
    # template_engine.render_nginx_conf at RENDER time — NOT here. Keeping this
    # converter ACL-free means templates stay mode-independent and re-conversion
    # of an already-v4 conf is idempotent (no stale scaffolding to strip).
    # ------------------------------------------------------------------
    return text


def convert_stream_conf(
    text: str,
    service_name_hint: str = "",
    compose_service_names: list[str] | None = None,
) -> str:
    """The STREAM conf's own conversion (task-doc R9.2 / GRILLING G42.1).

    A stream conf is not an http conf with a different listener, and running it
    through `convert_nginx` is a measured defect, not a style question:

    * `convert_nginx` wraps TLS blocks in an **ssl guard** (`{% if tls %}`) — but
      a stream block's TLS listener is STRUCTURAL and the file's existence is the
      switch, so the block must never be conditional;
    * it injects **`auth_basic`** — a directive the stream module does not have,
      which makes the conf fail `nginx -t` for a password-protected instance
      (the renderer strips those only when the instance has NO service password);
    * it rewrites **`server_name`** to `{{ hostname }}`, the *instance* host —
      while a stream block is selected by the **canonical name**, the name the
      edge dials (R4.4/R5.1).

    What DOES apply is the same substitution set the http path uses for these two
    things: the certificate paths (the store's real path, mounted at the same
    path in the internal nginx) and the container-name prefixing. The generated
    conf names its upstream by the COMPOSE service name (`proxy_pass
    fastapi-app:8100;`), and this rewrites that host to
    `{{ container_prefix }}<name>` exactly as the http converter rewrites a
    `proxy_pass` host — one convention, two conf kinds.

    The platform POLICY is also this converter's: every block's allow/deny is
    replaced by `allow {{ stream_allow_subnet }}; deny all;` (R8), and the
    certificate pair is covered per block (R5/R6/R9).
    """
    # R5/R6/R8/R9 — certificate coverage (a stream conf has no file-level
    # certificate context, so a file-level pair is removed) and the platform
    # policy placeholder pair. Applied before the name/upstream rewrites; server
    # spans are unaffected by either.
    text = _stream_cert_and_policy(text)

    # G56 (D7) — `server_name` is TEMPLATED, exactly like the http category's.
    # A stream block is selected by the canonical name the edge dials; baking it
    # verbatim made a conf instance-bound for no reason. The name is rebuilt from
    # its `<stem>--<sub>.<domain>` shape with the -api's own variables, so a conf
    # from another deployment can be reused and renders with THIS instance's
    # names. A token that cannot yield a sub-service is refused: the converter
    # cannot invent the block's identity.
    def _rewrite_stream_server_name(m: "re.Match[str]") -> str:
        head, token, tail = m.group(1), m.group(2), m.group(3)
        body = token.strip()
        if "{{" in body:
            subs = re.findall(r"--([A-Za-z0-9_-]+)\.", body)
            if len(subs) != 1:
                raise ValueError(
                    f"stream server_name {body!r} cannot be parsed into "
                    "'--<sub_service>.<domain>' — the conf must name one sub-service per block"
                )
            return f"{head}{{{{ hostname_stem }}}}--{subs[0]}.{{{{ domain_name }}}}{tail}"
        names: list[str] = []
        for name in body.split():
            parsed = re.match(r"^.*?--([A-Za-z0-9_-]+)\.(.+?)\s*$", name)
            if not parsed:
                raise ValueError(
                    f"stream server_name {name!r} cannot be parsed into "
                    "'--<sub_service>.<domain>' — the conf must name one sub-service per block"
                )
            names.append("{{ hostname_stem }}--%s.{{ domain_name }}" % parsed.group(1))
        return head + " ".join(names) + tail

    text = re.sub(
        r"([ \t]*server_name[ \t]+)([^;\n]+)(;)",
        _rewrite_stream_server_name,
        text,
    )

    # The upstream `set $upstream <host>:<port>;` — the stream conf's equivalent
    # of a proxy_pass target. Rewritten only when the host IS a compose service
    # name, like the http path (no heuristics, no prefix stripping).
    compose_names: set[str] = set()
    if compose_service_names:
        compose_names = {n.lower() for n in compose_service_names}
    if compose_names:
        def _repl_set(m: re.Match) -> str:
            host = m.group(2)
            if host.lower() in compose_names:
                return f"{m.group(1)}{{{{ container_prefix }}}}{host}{m.group(3)}"
            return m.group(0)

        text = re.sub(
            r'(set\s+\$[A-Za-z0-9_]+\s+)([a-zA-Z0-9_-]+)((?::\d+)?\s*;)',
            _repl_set,
            text,
        )

    # ---- Legacy variable upstream → STATIC (G56 follow-up, 2026-10-23) ----
    # A historical stream conf may carry the old deferred-resolution form:
    #
    #   set $stream_upstream <host>:<port>;
    #   resolver 127.0.0.11 ...;
    #   proxy_pass $stream_upstream;
    #
    # That form DEFEATS the SNI-based choice of virtual server (every SNI lands
    # on the first block) and, on the shipped internal nginx, can evaluate
    # empty — measured 2026-10-23: `no host in upstream ""`, every connection
    # 500 while the card and the mint looked healthy. The current generator
    # writes a STATIC pass; a selected historical conf is normalized to the
    # same shape here, so the converter's output is one form.
    # The mapping MUST be per server block: the historical conf reuses the
    # same variable name (`$stream_upstream`) in EVERY block with a different
    # target, so a conf-wide map collapsed both to the last one — measured in
    # this round, where the neo4j block was rewritten to falkordb and then
    # correctly dropped by the profile filter, leaving an empty stream conf.
    def _normalize_block(block: str) -> str:
        targets = {
            m.group(1): m.group(2).strip()
            for m in re.finditer(
                r"(?m)^[ \t]*set[ \t]+\$([A-Za-z0-9_]+)[ \t]+([^;\n]+);", block
            )
        }
        used: set[str] = set()

        def _static_pass(m: "re.Match[str]") -> str:
            var = m.group(2)
            target = targets.get(var)
            if target is None:
                return m.group(0)
            used.add(var)
            return f"{m.group(1)}proxy_pass {target}{m.group(3)}"

        out = re.sub(
            r"(?m)^([ \t]*)proxy_pass[ \t]+\$([A-Za-z0-9_]+)[ \t]*(;)",
            _static_pass,
            block,
        )
        if used:
            out = re.sub(
                r"(?m)^[ \t]*set[ \t]+\$([A-Za-z0-9_]+)[ \t]+[^;\n]+;\n?",
                lambda m: "" if m.group(1) in used else m.group(0),
                out,
            )
            # The resolver is only needed by the variable form.
            out = re.sub(r"(?m)^[ \t]*resolver[ \t]+[^;\n]+;\n?", "", out)
        return out

    spans: list[tuple[int, int]] = []
    for m in re.finditer(r"(?m)^[ \t]*server[ \t]*\{", text):
        depth = 0
        i = m.end() - 1
        while i < len(text):
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    spans.append((m.start(), i + 1))
                    break
            i += 1
    if spans:
        rebuilt: list[str] = []
        cursor = 0
        for start, end in spans:
            rebuilt.append(text[cursor:start])
            rebuilt.append(_normalize_block(text[start:end]))
            cursor = end
        rebuilt.append(text[cursor:])
        text = "".join(rebuilt)

    # A STATIC `proxy_pass <compose-service>:<port>;` (the shape the generator
    # writes) gets the same prefix as the `set` form. Run after the legacy
    # normalization so a converted historical conf is covered too. Already-
    # prefixed targets contain `{{`, which this pattern cannot match — so a
    # second conversion is a no-op.
    if compose_names:
        def _repl_static(m: re.Match) -> str:
            host = m.group(2)
            if host.lower() in compose_names:
                return f"{m.group(1)}{{{{ container_prefix }}}}{host}{m.group(3)}"
            return m.group(0)

        text = re.sub(
            r"(?m)^([ \t]*proxy_pass[ \t]+)([a-zA-Z0-9_-]+)((?::\d+)?[ \t]*;)",
            _repl_static,
            text,
        )

    # Everything else is deliberately untouched: `listen … ssl` stays
    # unconditional and no auth_basic is injected. `server_name` is templated
    # above (G56); the policy and certificate rules live in
    # `_stream_cert_and_policy`.
    return text


def make_header(filename: str, service_name_hint: str) -> str:
    hint = service_name_hint or filename
    return _HEADER_TPL.format(stem=filename, hint=hint)


def nginx_file_to_template(
    input_path: str,
    output_path: str,
    service_name_hint: str = "",
    compose_service_names: list[str] | None = None,
) -> None:
    """Convert a plain nginx conf file to a Jinja2 template and write output_path.

    Parameters
    ----------
    compose_service_names:
        Service keys from the companion docker-compose.yml.  Passed through to
        :func:`convert_nginx` so proxy_pass targets matching a compose service
        name are rewritten to ``{{ container_prefix }}<name>``.
    """
    src = Path(input_path)
    text = src.read_text()
    hint = service_name_hint or src.stem
    header = make_header(src.name, hint)
    converted = convert_nginx(text, hint, compose_service_names)
    Path(output_path).write_text(header + converted)
    # Mark as generated so gateway UI shows it under "Generated Files"
    Path(str(output_path) + ".generated").write_text("")

"""lib/nginx_converter.py — convert a plain nginx conf to a Jinja2 .j2 template.

Transformations applied
-----------------------
directive           before                              after
---------           ------                              -----
server_name         server_name example.com;            server_name {{ hostname }};
server_name         server_name web_hostname--neo4j;    server_name {{ hostname_stem }}--neo4j.{{ domain_name }};
                    (a name carrying `--` — R1.5's extra HTTP endpoint — keeps its
                     sub-service instead of collapsing to the instance host)
auth_basic          auth_basic "My App";                auth_basic "{{ service_name }} - {{ user_name }}";
auth_basic_user_file auth_basic_user_file /etc/...;     auth_basic_user_file {{ htpasswd_path }};
proxy_pass          proxy_pass http://web:80;           proxy_pass http://{{ container_prefix }}web:80;
                    (only when host matches a compose service name exactly)

All other content is preserved verbatim.  ${ENV_VAR} expressions are left
untouched — they are resolved by nginx at runtime via environment substitution.
"""

from __future__ import annotations

import re
from pathlib import Path

_HEADER_TPL = """\
# {stem}.nginx.conf.j2 — generated by gen_nginx_template.py
#
# Template variables resolved at registration time by user_provision_tool:
#   {{{{ hostname }}}}          e.g. {hint}-alice-0.example.com
#   {{{{ container_prefix }}}}  e.g. {hint}-user_alice-0-
#   {{{{ htpasswd_path }}}}     absolute path to the generated .htpasswd file
#   {{{{ user_name }}}}
#   {{{{ service_name }}}}
#   {{{{ label }}}}
#   {{{{ domain_name }}}}
#   {{{{ network_name }}}}
#   {{{{ https }}}}             boolean, True when HTTPS is enabled
#   {{{{ ssl_certificate_path }}}}      /provision/ssl/{{{{ domain_name }}}}/fullchain.pem
#   {{{{ ssl_certificate_key_path }}}}  /provision/ssl/{{{{ domain_name }}}}/privkey.pem
#
# NOTE: proxy_pass targets that exactly match a compose service name have
#   been rewritten to {{{{ container_prefix }}}}<name>.  Any host that does
#   not match a compose service name is left unchanged — review and adjust
#   remaining literal container names manually.
#
# NOTE: ssl_certificate and ssl_certificate_key paths have been replaced with
#   template variables.  Wrap HTTPS server blocks in {{% if tls %}}...{{% endif %}}
#   to conditionally enable TLS.
#
"""


def convert_nginx(
    text: str,
    service_name_hint: str = "",
    compose_service_names: list[str] | None = None,
) -> str:
    """Apply Jinja2 substitutions to the text of a plain nginx conf.

    Parameters
    ----------
    service_name_hint:
        Provision service name (used only for the generated header comment).
    compose_service_names:
        Service keys from the companion docker-compose.yml.  This is the
        **only** input used to rewrite proxy_pass targets.  Each host that
        exactly matches a compose service name is replaced with
        ``{{ container_prefix }}<name>`` so it resolves to the actual
        deployed container name at render time.

        If empty or ``None``, proxy_pass targets are left unchanged — the
        caller should review and adjust container names manually.
    """

    # server_name — the PRIMARY's name becomes the instance host; a name carrying
    # R1.5's reserved separator keeps its sub-service and becomes
    # `<instance stem>--<sub_service>.<domain>` (one label under the domain, which
    # is what lets the single wildcard certificate serve it).
    #
    # Before this, EVERY token became `{{ hostname }}` — so a block declaring
    # `<host>--neo4j.<domain>` was flattened back to the instance host at render
    # time, the endpoint the row declares ceased to exist, and `validate_conf`
    # (R1.3) could never pass. Measured 2026-10-10; see round 2's F47.
    def _server_name(match: "re.Match[str]") -> str:
        head, token, tail = match.group(1), match.group(2), match.group(3)
        parts: list[str] = []
        for name in token.split():
            if "--" in name:
                # Everything after the separator, minus any domain the model
                # wrote: a sub-service is a compose service key and carries no dot.
                sub = name.split("--", 1)[1].split(".")[0].strip()
                parts.append(
                    f"{{{{ hostname_stem }}}}--{sub}.{{{{ domain_name }}}}"
                    if sub else "{{ hostname }}"
                )
            else:
                parts.append("{{ hostname }}")
        return head + " ".join(parts) + tail

    text = re.sub(r'([ \t]*server_name[ \t]+)([^\n;]+)(;)', _server_name, text)

    # auth_basic string
    text = re.sub(
        r'([ \t]*auth_basic[ \t]+)"[^"]*"(;)',
        r'\1"{{ service_name }} - {{ user_name }}"\2',
        text,
    )

    # auth_basic_user_file path
    text = re.sub(
        r'([ \t]*auth_basic_user_file[ \t]+)\S+(;)',
        r'\1{{ htpasswd_path }}\2',
        text,
    )

    # ssl_certificate path → {{ ssl_certificate_path }}
    text = re.sub(
        r'([ \t]*ssl_certificate[ \t]+)\S+(;)',
        r'\1{{ ssl_certificate_path }}\2',
        text,
    )

    # ssl_certificate_key path → {{ ssl_certificate_key_path }}
    text = re.sub(
        r'([ \t]*ssl_certificate_key[ \t]+)\S+(;)',
        r'\1{{ ssl_certificate_key_path }}\2',
        text,
    )

    # --- Build set of compose service names for fast lookup ---
    compose_names: set[str] = set()
    if compose_service_names:
        compose_names = {n.lower() for n in compose_service_names}

    # --- Wrap / auto-generate HTTPS server blocks ---
    # Helper to split text into server blocks (preserving non-server content).
    def _split_server_blocks(t: str):
        blocks = re.split(r'(^[ \t]*server\s*\{)', t, flags=re.MULTILINE)
        result: list[dict[str, Any]] = []
        i = 0
        while i < len(blocks):
            chunk = blocks[i]
            if re.match(r'^[ \t]*server\s*\{', chunk):
                # Collect the full server block via brace counting
                block = chunk
                depth = chunk.count('{') - chunk.count('}')
                i += 1
                while i < len(blocks) and depth > 0:
                    next_chunk = blocks[i]
                    depth += next_chunk.count('{') - next_chunk.count('}')
                    block += next_chunk
                    i += 1
                result.append({"is_server": True, "text": block})
            else:
                if chunk:
                    result.append({"is_server": False, "text": chunk})
                i += 1
        return result

    _has_ssl_listen = bool(re.search(r'listen\s+[^;]*\bssl\b', text))
    if _has_ssl_listen:
        # Existing HTTPS blocks: wrap them + redirect blocks in {% if tls %}.
        parts = _split_server_blocks(text)
        out: list[str] = []
        for p in parts:
            if p["is_server"]:
                block = p["text"]
                if re.search(r'listen\s+[^;]*\bssl\b', block):
                    out.append('\n{% if tls %}\n' + block + '\n{% endif %}\n')
                elif re.search(r'return\s+301\s+https://', block):
                    out.append('\n{% if tls %}\n' + block + '\n{% endif %}\n')
                else:
                    out.append(block)
            else:
                out.append(p["text"])
        text = ''.join(out)
    else:
        # No HTTPS blocks in source → auto-generate them from HTTP blocks.
        parts = _split_server_blocks(text)
        out: list[str] = []
        for p in parts:
            if p["is_server"]:
                block = p["text"]
                # Only auto-generate HTTPS for blocks with listen 80 (not other ports).
                if re.search(r'listen\s+[^;]*\b80\b', block) and not re.search(r'listen\s+[^;]*\bssl\b', block):
                    https_block = block
                    # Replace listen 80 (with optional modifiers) → listen 443 ssl
                    https_block = re.sub(
                        r'listen\s+80(\s+[^;]*)?;',
                        r'listen 443 ssl\1;',
                        https_block,
                    )
                    # Inject ssl_certificate directives after the listen 443 ssl line
                    https_block = re.sub(
                        r'(listen\s+443\s+ssl[^;]*;)',
                        r'\1\n    ssl_certificate {{ ssl_certificate_path }};\n    ssl_certificate_key {{ ssl_certificate_key_path }};',
                        https_block,
                    )
                    out.append(block)
                    out.append('\n{% if tls %}\n' + https_block + '\n{% endif %}\n')
                else:
                    out.append(block)
            else:
                out.append(p["text"])
        text = ''.join(out)

    # proxy_pass — rewrite host to {{ container_prefix }}<name> when it
    # exactly matches a compose service name.  This is deterministic: the
    # original docker-compose.yml defines the service names, and the
    # original nginx.conf references them.  No heuristics, no prefix stripping.
    if compose_names:

        def _repl_proxy(m: re.Match) -> str:
            scheme = m.group(1)      # "http://" or "https://"
            host = m.group(2)        # container name or hostname
            port_path = m.group(3)   # ":port" and/or "/path", may be empty
            tail = m.group(4)        # ";" or whitespace terminator

            if host.lower() in compose_names:
                return (
                    f"proxy_pass {scheme}"
                    f"{{{{ container_prefix }}}}{host}{port_path}{tail}"
                )
            return m.group(0)

        text = re.sub(
            r'proxy_pass\s+(https?://)([a-zA-Z0-9_-]+)((?::\d+)?(?:/[^\s;]*)?)(;)',
            _repl_proxy,
            text,
        )

    # --- Inject auth_basic into every server block that lacks it ---
    # Must run AFTER HTTPS block generation so that:
    #  - auto-generated HTTPS blocks (cloned from HTTP) also receive auth_basic
    #  - existing HTTPS blocks (wrapped in {% if tls %}) also receive auth_basic
    if not re.search(r'[ \t]*auth_basic\b', text):
        def _inject_auth(m: re.Match) -> str:
            indent = re.match(r'^([ \t]*)', m.group(0)).group(1)
            auth_lines = (
                indent + 'auth_basic "{{ service_name }} - {{ user_name }}";\n' +
                indent + 'auth_basic_user_file {{ htpasswd_path }};\n'
            )
            return auth_lines + m.group(0)

        parts = _split_server_blocks(text)
        out_blocks: list[str] = []
        for p in parts:
            if p["is_server"]:
                block = p["text"]
                # Inject auth_basic before the first proxy_pass in this server block
                block = re.sub(
                    r'([ \t]*)proxy_pass[ \t]+[^;]+;',
                    _inject_auth,
                    block,
                    count=1,
                )
                out_blocks.append(block)
            else:
                out_blocks.append(p["text"])
        text = ''.join(out_blocks)

    # ------------------------------------------------------------------
    # v4 (acl-enforcement-design-v4 §10.3 F2): the per-service conf is
    # byte-identical across modes, and the JWT/ACL scaffolding (set $auth_mode,
    # include env.d, auth_request, /__basic__/, @auth_401/@auth_403, the plain
    # _set_token proxy, the variable /_auth_jwt) is injected by
    # template_engine.render_nginx_conf at RENDER time — NOT here. Keeping this
    # converter ACL-free means templates stay mode-independent and re-conversion
    # of an already-v4 conf is idempotent (no stale scaffolding to strip).
    # ------------------------------------------------------------------
    return text


def convert_stream_conf(
    text: str,
    service_name_hint: str = "",
    compose_service_names: list[str] | None = None,
) -> str:
    """The STREAM conf's own conversion (task-doc R9.2 / GRILLING G42.1).

    A stream conf is not an http conf with a different listener, and running it
    through `convert_nginx` is a measured defect, not a style question:

    * `convert_nginx` wraps TLS blocks in an **ssl guard** (`{% if tls %}`) — but
      a stream block's TLS listener is STRUCTURAL and the file's existence is the
      switch, so the block must never be conditional;
    * it injects **`auth_basic`** — a directive the stream module does not have,
      which makes the conf fail `nginx -t` for a password-protected instance
      (the renderer strips those only when the instance has NO service password);
    * it rewrites **`server_name`** to `{{ hostname }}`, the *instance* host —
      while a stream block is selected by the **canonical name**, the name the
      edge dials (R4.4/R5.1).

    What DOES apply is the same substitution set the http path uses for these two
    things: the certificate paths (the store's real path, mounted at the same
    path in the internal nginx) and the container-name prefixing. The generated
    conf names its upstream by the COMPOSE service name (`set $upstream
    fastapi-app:8100;`), and this rewrites that host to
    `{{ container_prefix }}<name>` exactly as the http converter rewrites a
    `proxy_pass` host — one convention, two conf kinds.
    """
    # ssl_certificate / ssl_certificate_key → the template variables (identical
    # to the http path: the path is the deploy's own recorded certificate).
    text = re.sub(
        r'([ \t]*ssl_certificate[ \t]+)\S+(;)',
        r'\1{{ ssl_certificate_path }}\2',
        text,
    )
    text = re.sub(
        r'([ \t]*ssl_certificate_key[ \t]+)\S+(;)',
        r'\1{{ ssl_certificate_key_path }}\2',
        text,
    )

    # The upstream `set $upstream <host>:<port>;` — the stream conf's equivalent
    # of a proxy_pass target. Rewritten only when the host IS a compose service
    # name, like the http path (no heuristics, no prefix stripping).
    compose_names: set[str] = set()
    if compose_service_names:
        compose_names = {n.lower() for n in compose_service_names}
    if compose_names:
        def _repl_set(m: re.Match) -> str:
            host = m.group(2)
            if host.lower() in compose_names:
                return f"{m.group(1)}{{{{ container_prefix }}}}{host}{m.group(3)}"
            return m.group(0)

        text = re.sub(
            r'(set\s+\$[A-Za-z0-9_]+\s+)([a-zA-Z0-9_-]+)((?::\d+)?\s*;)',
            _repl_set,
            text,
        )

    # Everything else is deliberately untouched: `server_name` stays the
    # canonical name, `listen … ssl` stays unconditional, `allow/deny` and the
    # `resolver` stay as written, and no auth_basic is injected.
    return text


def make_header(filename: str, service_name_hint: str) -> str:
    hint = service_name_hint or filename
    return _HEADER_TPL.format(stem=filename, hint=hint)


def nginx_file_to_template(
    input_path: str,
    output_path: str,
    service_name_hint: str = "",
    compose_service_names: list[str] | None = None,
) -> None:
    """Convert a plain nginx conf file to a Jinja2 template and write output_path.

    Parameters
    ----------
    compose_service_names:
        Service keys from the companion docker-compose.yml.  Passed through to
        :func:`convert_nginx` so proxy_pass targets matching a compose service
        name are rewritten to ``{{ container_prefix }}<name>``.
    """
    src = Path(input_path)
    text = src.read_text()
    hint = service_name_hint or src.stem
    header = make_header(src.name, hint)
    converted = convert_nginx(text, hint, compose_service_names)
    Path(output_path).write_text(header + converted)
    # Mark as generated so gateway UI shows it under "Generated Files"
    Path(str(output_path) + ".generated").write_text("")

"""Backfill ``.generated`` markers for platform-written source-project files.

G93 / doc §2 A1.3 + A1.2 audit (T2/T3). Marker-first classification means a
file is a Template only when it has NO marker, so an unmarked platform artifact
is indistinguishable from a repo-authored file. This pass adds the missing
markers **only where the file can be attributed to a platform writer**:

1. its header names a platform generator (the compose / nginx converters and
   the gateway's stream-conf writer stamp a header), or
2. its name carries a job token (``gt-<12 hex>``), or
3. its name is a per-user rendered artifact (``*.user-<user>.<label>.*`` and
   ``.env.<n>.<user>.<label>``).

A platform-look-ing NAME alone (``nginx.conf.j2``) is never sufficient: the
audit reports such a file instead of marking it. Repo-origin files
(``nginx.two-endpoints.conf``, ``nginx.graphiti.conf``, committed fixtures)
stay unmarked.

Usage::

    python -m scripts.backfill_generated_markers --root /srv/... --dry-run
    python -m scripts.backfill_generated_markers --root /srv/... --apply
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

# The three platform writers' headers. The first line is enough, but a short
# prefix is read so a licence/annotation line above it does not hide it.
GENERATOR_HEADERS = (
    "generated by gen_compose_template.py",
    "generated by gen_nginx_template.py",
    "generated by gen_stream_conf",
    "Generated by the provision gateway",
)
HEADER_READ_BYTES = 4096

JOB_TOKEN_RE = re.compile(r"gt-[0-9a-f]{12}")
# docker-compose.user-<u>.<label>.yml | <svc>.user-<u>.<label>.<cat>.conf
# | <svc>.user-<u>.<label>.htpasswd | .env.<n>.<u>.<label>
PER_USER_RE = re.compile(
    r"(?:\.user-[^.]+\.\d+\.)|(?:^\.env\.\d+\.[^.]+\.\d+$)"
)
MARKER_SUFFIX = ".generated"
STATE_PREFIX = ".provision-state"


def _head(path: Path) -> str:
    try:
        with path.open("rb") as fh:
            return fh.read(HEADER_READ_BYTES).decode("utf-8", "replace")
    except OSError:
        return ""


def attribution_reason(path: Path) -> str | None:
    """Why this file belongs to a platform writer, or ``None`` if it does not.

    Deliberately strict: a name that merely LOOKS generated is not enough.
    """
    head = _head(path)
    for header in GENERATOR_HEADERS:
        if header in head:
            return f"generator header: {header}"
    name = path.name
    if JOB_TOKEN_RE.search(name):
        return "job token"
    if PER_USER_RE.search(name):
        return "per-user rendered name"
    return None


def is_platform_looking(path: Path) -> bool:
    """A name/extension the platform writes — used by the audit list."""
    name = path.name
    return (
        name.endswith(".j2")
        or bool(JOB_TOKEN_RE.search(name))
        or bool(PER_USER_RE.search(name))
    )


def _marker(path: Path) -> Path:
    return path.with_name(path.name + MARKER_SUFFIX)


def _skip(path: Path) -> bool:
    name = path.name
    return name.endswith(MARKER_SUFFIX) or name.startswith(STATE_PREFIX)


def scan(root: Path) -> list[dict]:
    """Return every unmarked file with its attribution verdict."""
    rows: list[dict] = []
    if not root.is_dir():
        return rows
    for path in sorted(root.rglob("*")):
        if not path.is_file() or _skip(path):
            continue
        if _marker(path).is_file():
            continue
        rows.append({
            "path": str(path.relative_to(root)),
            "attributed": attribution_reason(path),
            "platform_looking": is_platform_looking(path),
        })
    return rows


def backfill(root: Path, apply: bool = False) -> dict:
    rows = scan(root)
    marked: list[str] = []
    for row in rows:
        if row["attributed"]:
            if apply:
                (root / row["path"]).with_name(
                    Path(row["path"]).name + MARKER_SUFFIX).write_text("")
            marked.append(row["path"])
    unattributed = [
        r["path"] for r in rows
        if not r["attributed"] and r["platform_looking"]
    ]
    return {
        "root": str(root),
        "applied": apply,
        "marked": marked,
        "unattributed_platform_looking": unattributed,
        "unchanged": [r["path"] for r in rows if not r["attributed"]],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", default="/srv/provision_subnet_acl/source_projects",
        help="source-projects root (default: the -api's mount)")
    parser.add_argument("--apply", action="store_true",
                        help="write the markers (default: dry run)")
    parser.add_argument("--json", action="store_true",
                        help="print the full result as JSON")
    args = parser.parse_args(argv)
    result = backfill(Path(args.root), apply=args.apply)
    if args.json:
        print(json.dumps(result, indent=2))
    else:
        verb = "marked" if args.apply else "would mark"
        print(f"{verb} {len(result['marked'])} file(s)")
        for p in result["marked"]:
            print(f"  + {p}")
        if result["unattributed_platform_looking"]:
            print("platform-looking but NOT attributable (left unmarked):")
            for p in result["unattributed_platform_looking"]:
                print(f"  ? {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""G93/A1.3/T3 — the marker backfill marks only attributable files.

Marker-first classification (A1.2) makes an unmarked platform artifact look
repo-authored. The one-time pass may add a marker only when the file can be
attributed to a platform writer: a generator header, a job token, or a per-user
rendered name. A platform-looking NAME alone is never sufficient.
"""

from pathlib import Path

from scripts.backfill_generated_markers import (
    attribution_reason,
    backfill,
    is_platform_looking,
    scan,
)


def _write(path: Path, text: str = "") -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


class TestAttribution:
    def test_compose_header_attr(self, tmp_path):
        p = _write(tmp_path / "docker-compose.yml.j2",
                   "# myapp.yml.j2 — generated by gen_compose_template.py\n")
        assert "gen_compose_template.py" in (attribution_reason(p) or "")

    def test_nginx_header_attr(self, tmp_path):
        p = _write(tmp_path / "nginx.conf.j2",
                   "# myapp.nginx.conf.j2 — generated by gen_nginx_template.py\n")
        assert attribution_reason(p)

    def test_stream_header_attr(self, tmp_path):
        p = _write(tmp_path / "nginx.stream.base.0.conf.j2",
                   "# Generated by the provision gateway (one block per stream row).\n")
        assert "provision gateway" in (attribution_reason(p) or "")

    def test_job_token_attr(self, tmp_path):
        p = _write(tmp_path / "nginx.stream.fix.gt-0123456789ab.conf.j2",
                   "server {}\n")
        assert attribution_reason(p) == "job token"

    def test_per_user_name_attr(self, tmp_path):
        p = _write(tmp_path / "docker-compose.user-alice.0.yml", "services: {}\n")
        assert attribution_reason(p) == "per-user rendered name"

    def test_name_alone_is_not_sufficient(self, tmp_path):
        p = _write(tmp_path / "nginx.conf.j2", "server { listen 80; }\n")
        assert attribution_reason(p) is None
        assert is_platform_looking(p) is True

    def test_repo_plain_file_is_not_platform_looking(self, tmp_path):
        p = _write(tmp_path / "nginx.two-endpoints.conf", "server {}\n")
        assert attribution_reason(p) is None
        assert is_platform_looking(p) is False


class TestBackfill:
    def test_marks_only_attributable_and_is_idempotent(self, tmp_path):
        _write(tmp_path / "svc/docker-compose.yml.j2",
               "# x — generated by gen_compose_template.py\n")
        _write(tmp_path / "svc/nginx.conf.j2", "server {}\n")          # name only
        _write(tmp_path / "svc/nginx.two-endpoints.conf", "server {}\n")

        first = backfill(tmp_path, apply=True)
        assert "svc/docker-compose.yml.j2" in first["marked"]
        assert "svc/nginx.conf.j2" not in first["marked"]
        assert "svc/nginx.conf.j2" in first["unattributed_platform_looking"]
        assert (tmp_path / "svc/docker-compose.yml.j2.generated").is_file()
        assert not (tmp_path / "svc/nginx.conf.j2.generated").exists()
        assert not (tmp_path / "svc/nginx.two-endpoints.conf.generated").exists()

        second = backfill(tmp_path, apply=True)
        assert second["marked"] == []           # already marked: nothing to redo

    def test_dry_run_writes_nothing(self, tmp_path):
        _write(tmp_path / "svc/docker-compose.yml.j2",
               "# x — generated by gen_compose_template.py\n")
        result = backfill(tmp_path, apply=False)
        assert result["marked"] == ["svc/docker-compose.yml.j2"]
        assert not (tmp_path / "svc/docker-compose.yml.j2.generated").exists()

    def test_scan_reports_platform_looking_unmarked(self, tmp_path):
        root = tmp_path / "recipes"
        _write(root / "nginx.conf.j2", "server {}\n")
        _write(root / "nginx.two-endpoints.conf", "server {}\n")
        rows = scan(root)
        assert [r["path"] for r in rows] == [
            "nginx.conf.j2", "nginx.two-endpoints.conf"]
        assert rows[0]["platform_looking"] is True
        assert rows[1]["platform_looking"] is False
